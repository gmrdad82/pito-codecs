const fn zigzag8() -> [u8; 64] {
    let mut out = [0u8; 64];
    let mut k = 0;
    let mut d: i32 = 0;
    while d < 15 {
        let mut i: i32 = 0;
        while i < 8 {
            let (row, col) = if d % 2 == 0 { (d - i, i) } else { (i, d - i) };
            if row >= 0 && row < 8 && col >= 0 && col < 8 {
                out[k] = (row * 8 + col) as u8;
                k += 1;
            }
            i += 1;
        }
        d += 1;
    }
    out
}

