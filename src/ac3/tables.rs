fn bessel_i0(x: f64) -> f64 {
    let mut sum = 1.0;
    let mut term = 1.0;
    let q = x * x / 4.0;
    for k in 1..64 {
        term *= q / (k * k) as f64;
        sum += term;
        if term < sum * 1e-17 {
            break;
        }
    }
    sum
}

pub fn window() -> &'static [f32; 256] {
    static WINDOW: std::sync::LazyLock<[f32; 256]> = std::sync::LazyLock::new(|| {
        let mut w = [0f64; 257];
        let mut total = 0.0;
        for (n, v) in w.iter_mut().enumerate() {
            let r = 2.0 * n as f64 / 256.0 - 1.0;
            total += bessel_i0(std::f64::consts::PI * 5.0 * (1.0 - r * r).max(0.0).sqrt());
            *v = total;
        }
        let mut out = [0f32; 256];
        for (o, v) in out.iter_mut().zip(&w) {
            *o = (v / total).sqrt() as f32;
        }
        out
    });
    &WINDOW
}

