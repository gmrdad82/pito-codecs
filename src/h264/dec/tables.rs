pub const fn norm_adjust4(m: usize, pos: usize) -> u16 {
    let (i, j) = (pos / 4, pos % 4);
    if i % 2 == 0 && j % 2 == 0 {
        NORM_ADJUST4[m][0]
    } else if i % 2 == 1 && j % 2 == 1 {
        NORM_ADJUST4[m][1]
    } else {
        NORM_ADJUST4[m][2]
    }
}

pub const fn norm_adjust8(m: usize, pos: usize) -> u16 {
    let (i, j) = (pos / 8, pos % 8);
    let k = if i % 4 == 0 && j % 4 == 0 {
        0
    } else if i % 2 == 1 && j % 2 == 1 {
        1
    } else if i % 4 == 2 && j % 4 == 2 {
        2
    } else if (i % 4 == 0 && j % 2 == 1) || (i % 2 == 1 && j % 4 == 0) {
        3
    } else if (i % 4 == 0 && j % 4 == 2) || (i % 4 == 2 && j % 4 == 0) {
        4
    } else {
        5
    };
    NORM_ADJUST8[m][k]
}

